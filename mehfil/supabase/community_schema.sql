-- MEHFIL community storage for Supabase PostgreSQL.
-- Fresh Community start: no historical Render community rows are imported.
-- The Node server must use a server-side secret (never expose service_role to browsers).

create table if not exists public.community_messages (
  id bigint generated by default as identity primary key,
  user_name text not null default 'Musafir' check (char_length(user_name) <= 60),
  user_avatar text not null default '🎶' check (char_length(user_avatar) <= 12),
  mood text not null default 'love'
    check (mood in ('love', 'dard', 'sukoon', 'safar', 'happy', 'late-night')),
  text text not null check (char_length(text) between 1 and 1000),
  is_shayari boolean not null default false,
  likes integer not null default 0 check (likes >= 0),
  "timestamp" bigint not null,
  owner_id text,
  edited_at bigint
);

create index if not exists idx_community_messages_timestamp
  on public.community_messages ("timestamp" desc, id desc);

-- Keep this table server-only. The Express API validates the MEHFIL client
-- identity and enforces owner-only edit/delete operations.
alter table public.community_messages enable row level security;

-- Intentionally no anon/authenticated policies. Server-side service_role
-- access bypasses RLS; do not put that key in client-side code.

-- Atomic likes prevent lost increments under concurrent requests.
create or replace function public.like_community_message(message_id bigint)
returns setof public.community_messages
language sql
security invoker
set search_path = public
as $$
  update public.community_messages
  set likes = likes + 1
  where id = message_id
  returning *;
$$;

revoke all on function public.like_community_message(bigint) from public, anon, authenticated;
grant execute on function public.like_community_message(bigint) to service_role;
